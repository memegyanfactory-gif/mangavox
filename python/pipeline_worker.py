#!/usr/bin/env python3
"""
MangaVox Pipeline Worker
Reads a job JSON file, runs OCR → TTS → sync → video stages.
Communicates via JSON lines on stdout.
Usage: python pipeline_worker.py <job.json>
"""
import sys
import json
import os
import traceback

def emit(obj):
    """Emit a JSON line to stdout for the Electron host."""
    print(json.dumps(obj), flush=True)

def emit_progress(stage, current, total):
    emit({"type": "progress", "stage": stage, "current": current, "total": total, "percent": round(current / max(total, 1) * 100, 1)})

def emit_stage_complete(stage, data=None):
    emit({"type": "stage_complete", "stage": stage, "data": data or {}})

def emit_error(stage, message, recoverable=False):
    emit({"type": "error", "stage": stage, "message": message, "recoverable": recoverable})


def abort_pipeline(stage, message, recoverable=False):
    """Emit error and exit so the Electron host gets a non-zero exit code."""
    emit_error(stage, message, recoverable=recoverable)
    sys.exit(1)

def emit_done(outputs):
    emit({"type": "done", "outputs": outputs})

def load_cached_stage(output_dir, filename):
    """Load a previously saved stage result from disk (for resume support)."""
    path = os.path.join(output_dir, filename)
    if os.path.exists(path):
        with open(path, 'r') as f:
            return json.load(f)
    return None


def load_beats(output_dir):
    """Load panel-level beats from whichever narration file has them.

    The narrator writes narration.<provider>.json (gemini/g0i/ollama). Prefer a
    user-selected one if present, else the most recently modified that has beats.
    """
    candidates = []
    try:
        for name in os.listdir(output_dir):
            if name.startswith("narration") and name.endswith(".json") and "partial" not in name:
                candidates.append(os.path.join(output_dir, name))
    except Exception:
        return []
    # Newest first so a fresh re-narration wins.
    candidates.sort(key=lambda p: os.path.getmtime(p) if os.path.exists(p) else 0, reverse=True)
    for path in candidates:
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            beats = data.get("beats")
            if beats:
                return beats
        except Exception:
            continue
    return []


def load_script_segments(output_dir):
    """Load per-page script segments written by the Audio / Text tabs."""
    edited_path = os.path.join(output_dir, "script_edited.json")
    if os.path.exists(edited_path):
        with open(edited_path, 'r') as f:
            return json.load(f)
    return []


def load_existing_audio(output_dir):
    """Load audio files already generated by a prior TTS run."""
    import re
    audio_dir = os.path.join(output_dir, "audio")
    if not os.path.isdir(audio_dir):
        return []

    script = load_script_segments(output_dir)
    text_by_page = {int(s.get("page", i)): (s.get("text") or "") for i, s in enumerate(script)}

    out = []
    for fname in sorted(os.listdir(audio_dir)):
        if not fname.lower().endswith(('.wav', '.mp3', '.ogg', '.m4a')):
            continue
        m = re.search(r'page_(\d+)', fname, re.I)
        page = int(m.group(1)) if m else len(out)
        path = os.path.join(audio_dir, fname)
        if not os.path.isfile(path) or os.path.getsize(path) < 100:
            continue
        out.append({
            "page": page,
            "path": path,
            "text": text_by_page.get(page, text_by_page.get(page - 1, "")),
        })
    return out

def run_pipeline(job):
    pages_dir = job["pages_dir"]
    output_dir = job["output_dir"]
    stages = job.get("stages", ["ocr", "tts", "sync_map", "video"])
    tts_config = job.get("tts_config", {})
    video_config = job.get("video_config", {})
    ocr_engine_pref = job.get("ocr_engine", "vision")

    # Gemini API key (free tier — best quality when available)
    gemini_api_key = job.get("gemini_api_key", "")

    # Ollama vision config passed from Electron (user's selected model from Settings)
    ollama_config = None
    if job.get("ollama_url") and job.get("ollama_vision_model"):
        ollama_config = {
            "url": job["ollama_url"],
            "model": job["ollama_vision_model"],
            "temperature": job.get("ollama_vision_temperature", 0.3),
        }

    os.makedirs(output_dir, exist_ok=True)

    # Collect page image paths
    page_files = sorted([
        os.path.join(pages_dir, f) for f in os.listdir(pages_dir)
        if f.lower().endswith(('.jpg', '.jpeg', '.png', '.webp'))
    ])
    page_count = len(page_files)

    if not page_files:
        emit_error("init", f"No image files found in {pages_dir}")
        return

    emit({"type": "info", "message": f"Found {page_count} pages", "stages": stages})

    outputs = {}

    # ── Stage 1: OCR ──
    if "ocr" in stages:
        # Try to resume from cached OCR results
        cached_ocr = load_cached_stage(output_dir, "ocr_results.json")
        if cached_ocr:
            emit({"type": "info", "message": "Resuming from cached OCR results"})
            outputs["ocr"] = cached_ocr
            emit_stage_complete("ocr", {"page_count": len(cached_ocr), "resumed": True})
        else:
            try:
                from ocr_engine import run_ocr
                ocr_results = run_ocr(page_files, output_dir, emit_progress, engine_pref=ocr_engine_pref, ollama_config=ollama_config, gemini_api_key=gemini_api_key)
                outputs["ocr"] = ocr_results
                # Count pages that actually have text
                pages_with_text = sum(1 for r in ocr_results if r.get("texts"))
                emit_stage_complete("ocr", {"page_count": len(ocr_results), "pages_with_text": pages_with_text})

                if pages_with_text == 0:
                    emit({"type": "info", "message": "Warning: OCR found no text in any page. TTS/video stages may be empty."})
            except Exception as e:
                emit_error("ocr", str(e), recoverable=True)
                traceback.print_exc(file=sys.stderr)
                return

    # ── Stage 2: Text cleanup ──
    if "ocr" in stages:
        try:
            from text_cleanup import cleanup_texts
            cleaned = cleanup_texts(outputs.get("ocr", []))
            outputs["cleaned_text"] = cleaned
            emit_stage_complete("text_cleanup", {"segments": len(cleaned)})
        except Exception as e:
            emit_error("text_cleanup", str(e), recoverable=True)
            traceback.print_exc(file=sys.stderr)
            return

    # Check if we have any text to work with
    cleaned_text = outputs.get("cleaned_text", [])

    # If no cleaned_text from OCR stage, try loading user-edited script
    if not cleaned_text and "tts" in stages:
        edited_path = os.path.join(output_dir, "script_edited.json")
        if os.path.exists(edited_path):
            with open(edited_path, 'r') as f:
                cleaned_text = json.load(f)
            emit({"type": "info", "message": f"Loaded user-edited script ({len(cleaned_text)} segments)"})
        else:
            cached_ocr = load_cached_stage(output_dir, "ocr_results.json")
            if cached_ocr:
                try:
                    from text_cleanup import cleanup_texts
                    cleaned_text = cleanup_texts(cached_ocr)
                    emit({"type": "info", "message": f"Loaded cached OCR ({len(cleaned_text)} text segments)"})
                except Exception as e:
                    emit({"type": "info", "message": f"Text cleanup failed: {e}"})

    outputs["cleaned_text"] = cleaned_text

    if cleaned_text and page_count > 0:
        try:
            from pipeline_script import normalize_script_for_pages
            cleaned_text = normalize_script_for_pages(cleaned_text, page_count)
            outputs["cleaned_text"] = cleaned_text
            with open(os.path.join(output_dir, "script_edited.json"), "w", encoding="utf-8") as f:
                json.dump(cleaned_text, f, indent=2)
            emit({
                "type": "info",
                "message": f"Script aligned to {page_count} pages ({sum(1 for s in cleaned_text if (s.get('text') or '').strip())} with narration)",
            })
        except Exception as e:
            emit({"type": "info", "message": f"Script normalize skipped: {e}"})

    # TTS requires script text
    if "tts" in stages and not cleaned_text:
        emit_error("tts", "No script text found — generate a script in the Text/Audio tab first")
        return

    # sync_map / video without a TTS stage need audio already on disk
    if ("sync_map" in stages or "video" in stages) and "tts" not in stages and not outputs.get("audio"):
        existing_audio = load_existing_audio(output_dir)
        if existing_audio:
            outputs["audio"] = existing_audio
            emit({"type": "info", "message": f"Loaded {len(existing_audio)} existing audio file(s) from disk"})
        else:
            emit_error("init", "No audio files found — generate audio in the Audio tab first")
            return

    # ── Stage 3: TTS ──
    if "tts" in stages and cleaned_text:
        try:
            from tts_bridge import run_tts, resolve_tts_engine
            try:
                engine_choice = resolve_tts_engine(
                    tts_config.get("engine"), tts_config.get("voice"),
                )
                emit({
                    "type": "info",
                    "message": f"TTS engine: {engine_choice}",
                    "stage": "tts",
                    "engine": engine_choice,
                })
            except RuntimeError as exc:
                abort_pipeline("tts", str(exc), recoverable=False)

            tts_config = {**tts_config, "force_regen": tts_config.get("force_regen", True)}
            audio_files = run_tts(cleaned_text, output_dir, tts_config, emit_progress)
            outputs["audio"] = audio_files
            successful = sum(1 for a in audio_files if a.get("path") and os.path.exists(a["path"]))

            if successful == 0:
                # Surface a concrete reason rather than the generic "produced 0"
                first_err = next((a.get("error") for a in audio_files if a.get("error")), None)
                detail = f": {first_err}" if first_err else ""
                abort_pipeline(
                    "tts",
                    f"TTS produced 0 audio files out of {len(audio_files)} attempts{detail}",
                    recoverable=False,
                )

            emit_stage_complete("tts", {
                "audio_count": len(audio_files),
                "successful": successful,
                "engine": engine_choice,
            })
        except Exception as e:
            emit_error("tts", str(e), recoverable=True)
            traceback.print_exc(file=sys.stderr)
            return

    # ── Stage 4: Sync map ──
    if "sync_map" in stages:
        audio_files = outputs.get("audio") or load_existing_audio(output_dir)
        if not audio_files:
            emit_error("sync_map", "No audio files to sync — generate audio first")
            return
        try:
            from sync_map import generate_sync_map
            script = cleaned_text or load_script_segments(output_dir)
            beats = load_beats(output_dir)
            sync = generate_sync_map(script, audio_files, output_dir, page_count=page_count, beats=beats)
            outputs["sync_map"] = sync
            outputs["audio"] = audio_files
            emit_stage_complete("sync_map", {
                "segments": len(sync.get("segments", [])),
                "beats": len(sync.get("beat_segments", [])),
            })
        except Exception as e:
            emit_error("sync_map", str(e), recoverable=True)
            traceback.print_exc(file=sys.stderr)
            return

    # ── Stage 5: Video generation ──
    if "video" in stages:
        sync_map = outputs.get("sync_map")
        # Try loading sync map from disk if not in memory
        if not sync_map:
            sync_map = load_cached_stage(output_dir, "sync_map.json")
        if not sync_map or not sync_map.get("segments"):
            emit_error("video", "No sync map — run sync first or regenerate audio")
            return

        try:
            from video_generator import generate_video
            video_path = generate_video(
                page_files, sync_map, output_dir,
                config=video_config,
                progress_cb=emit_progress,
            )
            outputs["video"] = {"path": video_path}
            emit_stage_complete("video", {"path": video_path})
        except Exception as e:
            emit_error("video", str(e), recoverable=False)
            traceback.print_exc(file=sys.stderr)
            return

    emit_done(outputs)

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python pipeline_worker.py <job.json>", file=sys.stderr)
        sys.exit(1)

    job_path = sys.argv[1]
    try:
        with open(job_path, 'r') as f:
            job = json.load(f)
    except Exception as e:
        emit_error("init", f"Failed to read job file: {e}")
        sys.exit(1)

    try:
        run_pipeline(job)
    except Exception as e:
        emit_error("fatal", str(e))
        traceback.print_exc(file=sys.stderr)
        sys.exit(1)
